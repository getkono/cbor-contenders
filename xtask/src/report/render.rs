/// A Markdown table.
fn table(out: &mut String, header: &[&str], rows: &[Vec<String>]) {
    let _ = writeln!(out, "| {} |", header.join(" | "));
    let _ = writeln!(
        out,
        "|{}|",
        header.iter().map(|_| " --- ").collect::<Vec<_>>().join("|")
    );
    for row in rows {
        let _ = writeln!(out, "| {} |", row.join(" | "));
    }
    out.push('\n');
}

fn section(out: &mut String, id: &str, title: &str, text: &str) {
    let _ = writeln!(out, "<a id=\"{id}\"></a>\n\n## {title}\n");
    if !text.is_empty() {
        let _ = writeln!(out, "{text}\n");
    }
}

/// A count or size, with thousands grouped.
fn int(v: f64) -> String {
    let n = v.round() as i64;
    let digits = n.unsigned_abs().to_string();
    let mut grouped = String::new();
    for (i, c) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            grouped.push(' ');
        }
        grouped.push(c);
    }
    if n < 0 { format!("-{grouped}") } else { grouped }
}

fn opt(v: Option<f64>) -> String {
    v.map_or_else(|| "–".into(), int)
}

/// `value` as a multiple of `base`, `0.84×`.
fn ratio(value: Option<f64>, base: Option<f64>) -> String {
    match (value, base) {
        (Some(v), Some(b)) if b > 0.0 => format!("{:.2}×", v / b),
        _ => "–".into(),
    }
}

fn code(s: &str) -> String {
    format!("`{s}`")
}

/// Every entry measured per operation: baselines first.
fn entries() -> Vec<&'static str> {
    SETS.iter().flat_map(|s| s.backends.iter().copied()).collect()
}

/// The report.
pub fn render(data: &Data, verdicts: &[Verdict], exports: &[Export], notes: &[String]) -> String {
    let mut out = String::from("# Results\n\n");
    if data.pending {
        out.push_str(
            "Nothing has been measured yet: `results/` holds no measured file. Run `mise run all` \
             on a quiet x86-64 Linux host (`CC_TRUST=canonical mise run all` once it is quieted), \
             commit `results/`, and run `cargo xtask report`.\n\n",
        );
        verdict_section(&mut out, verdicts);
        return out;
    }
    out.push_str(
        "Generated by `cargo xtask report` from `results/`; the method is in the repository \
         [README](../README.md). Every figure is at the `portable` build (`-C target-cpu=x86-64`) \
         unless a table says otherwise.\n\n",
    );
    if !notes.is_empty() {
        out.push_str("**Draft.** These results are stale or incomplete:\n\n");
        for n in notes {
            let _ = writeln!(out, "- {n}");
        }
        out.push('\n');
    }
    verdict_section(&mut out, verdicts);
    kynos_section(data, &mut out);
    per_workload_section(data, &mut out);
    heap_section(data, &mut out);
    wire_section(data, &mut out);
    costs_section(data, &mut out);
    conformance_section(data, &mut out);
    model_section(data, &mut out);
    fuzz_section(data, &mut out);
    e2e_section(data, &mut out);
    exports_section(exports, &mut out);
    provenance_section(data, &mut out);
    out
}

fn verdict_section(out: &mut String, verdicts: &[Verdict]) {
    section(
        out,
        "verdict",
        "Verdict (kynos #989 section 7)",
        "CBOR is admitted in-tree only if every clause holds. Clause 1 was settled by kynos #998 \
         before anything here ran; the rest are computed from the results.",
    );
    let mut rows = Vec::new();
    for v in verdicts {
        let mut row = vec![code(v.entry), if v.admitted() { "yes".into() } else { "no".into() }];
        row.extend(v.clauses.iter().map(|c| c.word().to_owned()));
        rows.push(row);
    }
    table(
        out,
        &[
            "Candidate",
            "Admitted",
            "1 use case",
            "2 frontier",
            "3 conformance",
            "4 soundness",
            "5 licence",
        ],
        &rows,
    );
    section(out, "clauses", "The clauses, entry by entry", "");
    let mut rows = Vec::new();
    for v in verdicts {
        for (i, c) in v.clauses.iter().enumerate() {
            rows.push(vec![
                code(v.entry),
                (i + 1).to_string(),
                c.word().to_owned(),
                c.why().to_owned(),
            ]);
        }
    }
    table(out, &["Candidate", "Clause", "Outcome", "Why"], &rows);
}

fn kynos_section(data: &Data, out: &mut String) {
    section(
        out,
        "kynos",
        "Clause 2: axes 1–4 at the Kynos shapes",
        "Hardware `cycles:u` (median of rounds) and callgrind estimated cycles for the owned decode \
         of one shared frame and the `to_vec` encode, heap bytes per operation, and encoded bytes. \
         Ratios are against serde_json and prost; the A/A band is the widest gap between each \
         baseline and its copy.",
    );
    for workload in KYNOS {
        let _ = writeln!(out, "### {workload}\n");
        let mut rows = Vec::new();
        for entry in entries() {
            let mut row = vec![code(entry)];
            for axis in AXES {
                let mine = figure(data, axis, entry, workload);
                row.push(opt(mine));
                row.push(ratio(mine, figure(data, axis, "serde_json", workload)));
                row.push(ratio(mine, figure(data, axis, "prost", workload)));
                if axis.field == "cycles" {
                    row.push(opt(counted(data, axis, entry, workload)));
                }
            }
            rows.push(row);
        }
        let mut header = vec!["Entry"];
        for axis in AXES {
            header.extend([axis.name, "vs serde_json", "vs prost"]);
            if axis.field == "cycles" {
                header.push("est. cycles");
            }
        }
        table(out, &header, &rows);
        let bands: Vec<String> = AXES
            .iter()
            .filter(|a| a.field == "cycles")
            .flat_map(|a| {
                ["serde_json", "prost"].map(|b| {
                    format!(
                        "{} {b}: {}",
                        a.name,
                        aa_band(data, a, b, workload).map_or_else(|| "–".into(), |x| format!("{:.1} %", x * 100.0))
                    )
                })
            })
            .collect();
        let _ = writeln!(out, "A/A bands: {}.\n", bands.join("; "));
    }
}

fn per_workload_section(data: &Data, out: &mut String) {
    section(
        out,
        "workloads",
        "Every workload: estimated cycles",
        "callgrind estimated cycles (`Ir + 5·L1 misses + 35·LL misses`, fixed cache geometry) per \
         operation at `portable`, owned decode of a shared frame and `to_vec` encode, as a multiple \
         of serde_json's. Deterministic; the per-cell hardware cycles and every other shape are in \
         `data/hw.csv` and `data/callgrind.csv`. A dash is a cell not measured: a workload the \
         native formats do not carry, or a decode the entry refused (its verdict is in the CSV).",
    );
    for op in ["decode", "encode"] {
        let _ = writeln!(out, "### {op}\n");
        let mut rows = Vec::new();
        for workload in payloads::ALL {
            if op == "encode" && crate::matrix::DECODE_ONLY.contains(workload) {
                continue;
            }
            let base = data
                .callgrind
                .get(&Key::new(DECIDING_VARIANT, "serde_json", workload, op), "est_cycles");
            let mut row = vec![(*workload).to_owned(), opt(base)];
            for entry in entries().into_iter().skip(1) {
                let key = Key::new(DECIDING_VARIANT, entry, workload, op);
                let measurable = data
                    .callgrind
                    .row(&key)
                    .is_some_and(|r| r["verdict"] == "exact" || r["verdict"] == "inexact");
                row.push(if measurable {
                    ratio(data.callgrind.get(&key, "est_cycles"), base)
                } else {
                    "–".into()
                });
            }
            rows.push(row);
        }
        let mut header = vec!["Workload", "serde_json"];
        header.extend(entries().into_iter().skip(1));
        table(out, &header, &rows);
    }
}

fn heap_section(data: &Data, out: &mut String) {
    section(
        out,
        "heap",
        "Heap per operation",
        "Allocations and bytes per operation from the counting allocator, at `portable`, owned \
         decode of a shared frame and `to_vec` encode; every shape is in `data/alloc.csv`.",
    );
    let mut rows = Vec::new();
    for workload in KYNOS
        .iter()
        .chain(&["sweep-1kib", "sweep-64kib", "byte-strings", "numeric-arrays"])
    {
        for entry in entries() {
            let row = |op| data.host.alloc.row(&Key::new(DECIDING_VARIANT, entry, workload, op));
            let cell = |op, field: &str| opt(row(op).and_then(|r| r[field].as_f64()));
            rows.push(vec![
                (*workload).to_owned(),
                code(entry),
                cell("decode", "allocations"),
                cell("decode", "bytes"),
                cell("encode", "allocations"),
                cell("encode", "bytes"),
            ]);
        }
    }
    table(
        out,
        &[
            "Workload",
            "Entry",
            "Decode allocations",
            "Decode bytes",
            "Encode allocations",
            "Encode bytes",
        ],
        &rows,
    );
}

fn wire_section(data: &Data, out: &mut String) {
    section(
        out,
        "wire",
        "Axis 4: encoded size",
        "Bytes each entry writes for each workload's value with its defaults, raw, gzip level 6 and \
         zstd level 3, and whether the CBOR is preferred serialization (RFC 8949 section 4.1).",
    );
    let mut rows = Vec::new();
    for workload in payloads::ALL {
        for entry in entries() {
            if let Some(r) = data
                .wire
                .iter()
                .find(|r| r["backend"] == entry && r["workload"] == *workload)
            {
                rows.push(vec![
                    (*workload).to_owned(),
                    code(entry),
                    opt(r["raw"].as_f64()),
                    opt(r["gzip"].as_f64()),
                    opt(r["zstd"].as_f64()),
                    match r["preferred"].as_bool() {
                        Some(true) => "yes".into(),
                        Some(false) if crate::endtoend::format_of(entry) == codecs::Format::Cbor => "no".into(),
                        _ => "–".into(),
                    },
                ]);
            }
        }
    }
    table(out, &["Workload", "Entry", "Raw", "gzip", "zstd", "Preferred"], &rows);
}

fn costs_section(data: &Data, out: &mut String) {
    section(
        out,
        "costs",
        "What adopting one costs besides CPU",
        "`.text` added to a fixture that decodes and re-encodes the two Kynos body types (minus the \
         same program without a codec), clean and incremental compile times of that fixture \
         (median of its runs; adoption context, not an axis), whether the adapter builds on Rust \
         1.85 (Kynos's MSRV), the crates each adds and their `unsafe`, and their licences.",
    );
    let mut rows = Vec::new();
    for set in SETS {
        for (krate, _) in set.costs {
            let find = |rows: &[Value], variant: Option<&str>| {
                rows.iter()
                    .find(|r| r["crate"] == *krate && variant.is_none_or(|v| r["variant"] == v))
                    .cloned()
                    .unwrap_or(Value::Null)
            };
            let size = find(&data.host.size, Some(DECIDING_VARIANT));
            let compile = find(&data.host.compile_time, None);
            let msrv = find(&data.host.msrv, None);
            let foot = find(&data.footprint, None);
            let licences: std::collections::BTreeSet<String> = foot["crates"]
                .as_array()
                .into_iter()
                .flatten()
                .filter(|c| c["build_only"] == false)
                .filter_map(|c| c["licence"].as_str().map(str::to_owned))
                .collect();
            rows.push(vec![
                code(krate),
                opt(size["full_delta"].as_f64()),
                opt(size["decode_delta"].as_f64()),
                compile["release_s"]
                    .as_f64()
                    .map_or_else(|| "–".into(), |s| format!("{s:.1} s")),
                compile["incremental_s"]
                    .as_f64()
                    .map_or_else(|| "–".into(), |s| format!("{s:.2} s")),
                match msrv["builds_on_msrv"].as_bool() {
                    Some(true) => "yes".into(),
                    Some(false) => format!("no ({})", msrv["first_error"].as_str().unwrap_or("?")),
                    None => "–".into(),
                },
                msrv["declared"].as_str().unwrap_or("–").to_owned(),
                opt(foot["runtime_crates_added"].as_f64()),
                opt(foot["unsafe_blocks"].as_f64()),
                opt(foot["unsafe_fns"].as_f64()),
                licences.into_iter().collect::<Vec<_>>().join(", "),
            ]);
        }
    }
    table(
        out,
        &[
            "Crate",
            "`.text` full",
            "`.text` decode",
            "Clean release build",
            "Incremental dev",
            "Builds on 1.85",
            "Declared MSRV",
            "Runtime crates added",
            "`unsafe` blocks",
            "`unsafe` fns",
            "Licences",
        ],
        &rows,
    );
    let _ = writeln!(out, "Kynos's licence allow list: {}.\n", data.licences.join(", "));
}

#[expect(clippy::too_many_lines, reason = "three tables of one source")]
fn conformance_section(data: &Data, out: &mut String) {
    section(
        out,
        "conformance",
        "Conformance",
        "Gating failures per section and variant. A section's every disagreement and its first \
         listings are in `data/conformance.csv`; a gating failure is a silent difference (README, \
         Conformance).",
    );
    let mut sections: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    for report in data.host.conformance.values() {
        for entry in report["backends"].as_object().into_iter().flatten().map(|(_, e)| e) {
            sections.extend(
                entry["sections"]
                    .as_object()
                    .into_iter()
                    .flatten()
                    .map(|(k, _)| k.clone()),
            );
        }
    }
    let mut rows = Vec::new();
    for ((variant, set), report) in &data.host.conformance {
        for (name, entry) in report["backends"].as_object().into_iter().flatten() {
            let mut row = vec![
                code(name),
                variant.clone(),
                entry["gate"].as_str().unwrap_or("?").to_owned(),
            ];
            for s in &sections {
                row.push(opt(entry["sections"][s]["gating_failure_count"].as_f64()));
            }
            let _ = set;
            rows.push(row);
        }
    }
    let mut header = vec!["Candidate", "Variant", "Gate"];
    header.extend(sections.iter().map(String::as_str));
    table(out, &header, &rows);
    section(
        out,
        "conformance-failures",
        "First gating failures",
        "Up to ten per candidate and section, at `portable`.",
    );
    let mut rows = Vec::new();
    for ((variant, _), report) in data.host.conformance.iter().filter(|((v, _), _)| v == DECIDING_VARIANT) {
        for (name, entry) in report["backends"].as_object().into_iter().flatten() {
            let mut per_section: std::collections::BTreeMap<String, usize> = std::collections::BTreeMap::new();
            for f in entry["gating_failures"].as_array().into_iter().flatten() {
                let s = f["section"].as_str().unwrap_or("?").to_owned();
                let n = per_section.entry(s.clone()).or_default();
                *n += 1;
                if *n <= 10 {
                    rows.push(vec![
                        code(name),
                        variant.clone(),
                        s,
                        f["case"].as_str().unwrap_or("").replace('|', "\\|"),
                        f["detail"].as_str().unwrap_or("").replace('|', "\\|"),
                    ]);
                }
            }
        }
    }
    table(out, &["Candidate", "Variant", "Section", "Case", "Detail"], &rows);
    section(
        out,
        "trailing-depth",
        "Trailing bytes and nesting depth",
        "Whether each library's decode entry point refuses bytes after the item (as read from its \
         source; `wellformed` checks it), and the deepest nesting each accepted, into a value and \
         skipped, on 2 MiB and 8 MiB stacks (none is gated but a crash).",
    );
    let mut rows = Vec::new();
    if let Some(((_, _), _)) = data.host.conformance.iter().next() {
        for ((variant, _), report) in data.host.conformance.iter().filter(|((v, _), _)| v == DECIDING_VARIANT) {
            for (name, entry) in report["backends"].as_object().into_iter().flatten() {
                let limits = &entry["sections"]["depth"]["data"]["limits"]["backend"];
                let series = |s: &str| {
                    let l = &limits[s];
                    format!(
                        "{} / {} / {}",
                        l["max_accepted"].as_u64().map_or_else(|| "–".into(), |n| n.to_string()),
                        l["first_rejected"]
                            .as_u64()
                            .map_or_else(|| "–".into(), |n| n.to_string()),
                        l["first_crashed"]
                            .as_u64()
                            .map_or_else(|| "–".into(), |n| n.to_string()),
                    )
                };
                rows.push(vec![
                    code(name),
                    variant.clone(),
                    entry["trailing"].as_str().unwrap_or("?").to_owned(),
                    series("array/value/2MiB"),
                    series("array/ignored/2MiB"),
                    series("object/value/8MiB"),
                ]);
            }
        }
    }
    table(
        out,
        &[
            "Candidate",
            "Variant",
            "Trailing bytes",
            "Array into a value, 2 MiB (accepted / rejected / crashed)",
            "Array skipped, 2 MiB",
            "Map into a value, 8 MiB",
        ],
        &rows,
    );
}

fn model_section(data: &Data, out: &mut String) {
    section(
        out,
        "model",
        "Section 5: the JSON data model",
        "What each library does, bare, with the CBOR values the JSON data model has no place for, \
         and what the worked codec (`kynos-cbor`) answers. `schema` is what a faithful schema says \
         of the body; none means no schema Kynos derives is true of it, so the codec must refuse.",
    );
    let reports: Vec<(&String, &Value)> = data
        .host
        .conformance
        .iter()
        .filter(|((v, _), _)| v == DECIDING_VARIANT)
        .flat_map(|(_, r)| r["backends"].as_object().into_iter().flatten())
        .collect();
    let Some((_, first)) = reports.first() else {
        return;
    };
    let cases = first["sections"]["model"]["data"]["decode"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    let describe = |v: &Value| -> String {
        if let Some(a) = v.get("accept") {
            format!("accepts {}", a.to_string().replace('|', "\\|"))
        } else if let Some(r) = v.get("reject") {
            format!("refuses {}", r["status"])
        } else if v.get("panic").is_some() {
            "panics".into()
        } else {
            v.to_string()
        }
    };
    let mut rows = Vec::new();
    for (i, case) in cases.iter().enumerate() {
        let mut row = vec![
            case["case"].as_str().unwrap_or("").to_owned(),
            code(case["hex"].as_str().unwrap_or("")),
            case["schema"].as_str().unwrap_or("none").to_owned(),
            match &case["codec"] {
                Value::String(s) => s.clone(),
                v => format!("{} ({})", v["refused"], v["rule"].as_str().unwrap_or("")),
            },
        ];
        for (_, entry) in &reports {
            row.push(describe(&entry["sections"]["model"]["data"]["decode"][i]["library"]));
        }
        rows.push(row);
    }
    let mut header = vec!["Decode case", "Body", "Schema", "Worked codec"];
    header.extend(reports.iter().map(|(n, _)| n.as_str()));
    table(out, &header, &rows);
    let encodes = first["sections"]["model"]["data"]["encode"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    let mut rows = Vec::new();
    for (i, case) in encodes.iter().enumerate() {
        let mut row = vec![
            code(case["case"].as_str().unwrap_or("")),
            if case["faithful"] == true {
                "yes".into()
            } else {
                "no".into()
            },
        ];
        for (_, entry) in &reports {
            let e = &entry["sections"]["model"]["data"]["encode"][i];
            let library = e["library"]["hex"].as_str().map_or_else(|| "refuses".to_owned(), code);
            let codec = if e["codec"]["hex"].is_string() {
                "writes"
            } else {
                "refuses"
            };
            row.push(format!("{library}; codec {codec}"));
        }
        rows.push(row);
    }
    let mut header = vec!["Encode case", "Faithful"];
    header.extend(reports.iter().map(|(n, _)| n.as_str()));
    table(out, &header, &rows);
}

fn fuzz_section(data: &Data, out: &mut String) {
    section(
        out,
        "fuzz",
        "Fuzzing and Miri",
        "Each target for its full duration on two workers, continuing past every divergence; the \
         minimized corpus of each run is committed under `results/fuzz-corpus/`.",
    );
    let rows: Vec<Vec<String>> = data
        .fuzz
        .iter()
        .map(|r| {
            vec![
                code(r["backend"].as_str().unwrap_or("")),
                r["target"].as_str().unwrap_or("").to_owned(),
                opt(r["seconds"].as_f64()),
                if r["finished"] == true {
                    "yes".into()
                } else {
                    "no".into()
                },
                opt(r["crash_count"].as_f64()),
                r["assertion"]
                    .as_str()
                    .unwrap_or("")
                    .replace('|', "\\|")
                    .lines()
                    .next()
                    .unwrap_or("")
                    .to_owned(),
                r["crash_input_hex"].as_str().map(code).unwrap_or_default(),
                opt(r["corpus_files"].as_f64()),
            ]
        })
        .collect();
    table(
        out,
        &[
            "Candidate",
            "Target",
            "Seconds",
            "Finished",
            "Divergences",
            "First assertion",
            "Smallest input",
            "Corpus files",
        ],
        &rows,
    );
    let rows: Vec<Vec<String>> = data
        .miri
        .iter()
        .map(|r| {
            vec![
                code(r["set"].as_str().unwrap_or("")),
                r["outcome"].as_str().unwrap_or("").to_owned(),
                r["detail"].as_str().unwrap_or("").replace('|', "\\|"),
            ]
        })
        .collect();
    table(out, &["Set", "Miri", "Detail"], &rows);
}

#[expect(clippy::too_many_lines, reason = "the counted and the timed table")]
fn e2e_section(data: &Data, out: &mut String) {
    section(
        out,
        "e2e-counted",
        "End to end: counted per request",
        "callgrind estimated cycles per request through a Kynos server over an in-memory pipe, at \
         `portable`, and the codec's share: (entry − its format's floor) ÷ entry. A CBOR entry is \
         the worked codec, scan included.",
    );
    let est = |entry: &str, route: &str| {
        data.e2e_count
            .iter()
            .find(|r| r["backend"] == entry && r["route"] == route && r["variant"] == DECIDING_VARIANT)
            .and_then(|r| r["est_cycles"].as_f64())
    };
    let mut rows = Vec::new();
    for route in crate::endtoend::ROUTES {
        for set in SETS {
            for entry in crate::matrix::e2e_entries(set) {
                let mine = est(entry, route.0);
                let floor = est(crate::matrix::floor_of(entry), route.0);
                let share = match (mine, floor) {
                    (Some(m), Some(f)) if m > 0.0 => format!("{:.0} %", (m - f) / m * 100.0),
                    _ => "–".into(),
                };
                rows.push(vec![
                    route.0.to_owned(),
                    code(entry),
                    opt(mine),
                    opt(floor),
                    share,
                    ratio(mine, est("serde_json", route.0)),
                ]);
            }
        }
    }
    table(
        out,
        &["Route", "Entry", "Est. cycles", "Floor", "Codec share", "vs serde_json"],
        &rows,
    );
    section(
        out,
        "e2e-timed",
        "End to end: timed",
        "Closed-loop throughput at 64 connections and open-loop p99 at 70 % of serde_json's \
         throughput, median of reps, over loopback, against serde_json's and prost's A/A copies. \
         Section 6's cross-check: a timed gain far beyond what the counted codec share allows is a \
         measurement error to explain, not a result.",
    );
    let timed = |entry: &str, route: &str| {
        data.host
            .e2e_time
            .iter()
            .find(|r| r["backend"] == entry && r["route"] == route)
            .cloned()
    };
    let mut rows = Vec::new();
    for route in crate::endtoend::ROUTES {
        let base = timed("serde_json", route.0);
        for label in data
            .host
            .e2e_time
            .iter()
            .filter(|r| r["route"] == route.0)
            .filter_map(|r| r["backend"].as_str())
        {
            let Some(r) = timed(label, route.0) else { continue };
            let delta = |field: &str| match (r[field].as_f64(), base.as_ref().and_then(|b| b[field].as_f64())) {
                (Some(m), Some(b)) if b > 0.0 => format!("{:+.1} %", (m / b - 1.0) * 100.0),
                _ => "–".into(),
            };
            rows.push(vec![
                route.0.to_owned(),
                code(label),
                opt(r["rps"].as_f64()),
                delta("rps"),
                r["p99_ms"]
                    .as_f64()
                    .map_or_else(|| "–".into(), |p| format!("{p:.3} ms")),
                delta("p99_ms"),
                if r["saturated"] == true {
                    "yes".into()
                } else {
                    "no".into()
                },
                r["verdict"].as_str().unwrap_or("").to_owned(),
            ]);
        }
    }
    table(
        out,
        &[
            "Route",
            "Entry",
            "Throughput (rps)",
            "vs serde_json",
            "p99",
            "vs serde_json",
            "Saturated",
            "Verdict",
        ],
        &rows,
    );
}

fn exports_section(exports: &[Export], out: &mut String) {
    section(out, "exports", "Every result, as CSV", "");
    let rows: Vec<Vec<String>> = exports
        .iter()
        .map(|e| vec![format!("[`{0}`](data/{0})", e.name), e.what.clone(), e.rows.to_string()])
        .collect();
    table(out, &["File", "Holds", "Rows"], &rows);
}

fn provenance_section(data: &Data, out: &mut String) {
    section(
        out,
        "provenance",
        "Provenance",
        "Every result file read, with the code, host, compiler and load it was measured under.",
    );
    let rows: Vec<Vec<String>> = data
        .sources
        .iter()
        .map(|s| {
            let p = &s.provenance;
            vec![
                code(&s.name),
                s.skipped.clone().map_or_else(
                    || {
                        p["git_commit"]
                            .as_str()
                            .map(|c| c.chars().take(10).collect())
                            .unwrap_or_default()
                    },
                    |r| format!("skipped: {r}"),
                ),
                p["fingerprint"].as_str().unwrap_or("").to_owned(),
                p["timestamp"].as_str().unwrap_or("").to_owned(),
                p["cpu"].as_str().unwrap_or("").to_owned(),
                p["rustc"]
                    .as_str()
                    .and_then(|r| r.lines().next())
                    .unwrap_or("")
                    .to_owned(),
                p["trust"].as_str().unwrap_or("").to_owned(),
                p["loadavg"].as_str().unwrap_or("").to_owned(),
            ]
        })
        .collect();
    table(
        out,
        &[
            "File",
            "Commit",
            "Fingerprint",
            "Measured",
            "CPU",
            "Compiler",
            "Trust",
            "Load",
        ],
        &rows,
    );
}
